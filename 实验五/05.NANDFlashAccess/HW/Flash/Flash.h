#ifndef _FLASH_H_
#define _FLASH_H_

/*********************************************************************************************************
*                                              包含头文件
*********************************************************************************************************/
#include "DataType.h"

/*********************************************************************************************************
*                                              宏定义
*********************************************************************************************************/
//根据芯片的类型，决定每个PAGE的大小，大容量的为2K一个PAGE，小容量和中容量的为1K一个PAGE
#define FLASH_PAGE_SIZE       ((uint32_t)0x0800)                       //页大小
#define USER_FLASH_START_ADDR ((uint32_t)0x0807F000)                   //用户Flash起始地址，为第254页地址
#define USER_FLASH_ENDADDR USER_FLASH_START_ADDR + 2 * FLASH_PAGE_SIZE //用户Flash结束地址，大小为2页

/*********************************************************************************************************
*                                              结构体定义
*********************************************************************************************************/

/*********************************************************************************************************
*                                              API函数声明
*********************************************************************************************************/
void InitFlash(void);                                                  //初始化内部Flash模块
void FlashWriteWord(uint32_t startAddr, uint32_t* pBuf, uint32_t len); //向Flash中写入字
void FlashReadWord(uint32_t startAddr, uint32_t* pBuf, uint32_t len);  //从Flash读取字

#endif


