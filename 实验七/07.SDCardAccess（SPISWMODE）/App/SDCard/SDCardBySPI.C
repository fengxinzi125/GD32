/*********************************************************************************************************
* 函数名称：SDGetCID
* 函数功能：获取SD卡的CID信息，包括制造商信息
* 输入参数：cid：存放CID的内存，至少16Byte
* 输出参数：void
* 返 回 值：0-成功，其他-失败
* 创建日期：2021年07月01日
* 注    意：
*********************************************************************************************************/
u32 SDGetCID(u8* cid)
{
  u8 r1;

  //发CMD10命令，读CID
  r1 = SendCmd(CMD10, 0, 0x01);
  if(0x00 == r1)
  {
    //接收16个字节的数据
    r1 = RecvData(cid, 16);
  }

  //取消片选
  DisSelect();

  //校验
  if(r1)
  {
    return 1;
  }
  else 
  {
    return 0;
  }
}

