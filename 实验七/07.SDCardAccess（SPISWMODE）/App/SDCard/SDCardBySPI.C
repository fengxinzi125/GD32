/*********************************************************************************************************
* 函数名称：InitBSP
* 函数功能：硬件层初始化
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 创建日期：2021年07月01日
* 注    意：
*********************************************************************************************************/
static void InitBSP(void)
{
  //使能RCU相关时钟
  rcu_periph_clock_enable(RCU_GPIOC);  //使能GPIOC的时钟
  rcu_periph_clock_enable(RCU_GPIOD);  //使能GPIOD的时钟
  
  //CS
  gpio_init(GPIOC, GPIO_MODE_OUT_PP, GPIO_OSPEED_50MHZ, GPIO_PIN_11); //推完输出
  gpio_bit_set(GPIOC, GPIO_PIN_11);                                   //拉高片选
  
  //CLK
  gpio_init(GPIOC, GPIO_MODE_OUT_PP, GPIO_OSPEED_50MHZ, GPIO_PIN_12);  //推完输出
  gpio_bit_set(GPIOC, GPIO_PIN_12);                                    //拉高时钟线

  //MOSI
  gpio_init(GPIOD, GPIO_MODE_OUT_PP, GPIO_OSPEED_50MHZ, GPIO_PIN_2);  //推完输出
  gpio_bit_set(GPIOD, GPIO_PIN_2);                                    //MOSI默认输出高电平

  //MISO
  gpio_init(GPIOC, GPIO_MODE_IPU, GPIO_OSPEED_50MHZ, GPIO_PIN_8);     //上拉输入

  //CD
  gpio_init(GPIOD, GPIO_MODE_IPU, GPIO_OSPEED_50MHZ, GPIO_PIN_3);     //上拉输入
}

/*********************************************************************************************************
* 函数名称：ReadWriteByte
* 函数功能：读写单字节
* 输入参数：data：需要发送的数据
* 输出参数：void
* 返 回 值：读到的数据
* 创建日期：2021年07月01日
* 注    意：
*********************************************************************************************************/
static u8 ReadWriteByte(u8 data)
{
  u8 i, readData;

  readData = 0;
  for(i = 0; i < 8; i++)
  {
    //拉低时钟线
    gpio_bit_reset(GPIOC, GPIO_PIN_12); 

    //设置MOSI输出
    if(data & 0x80)
    {
      gpio_bit_set(GPIOD, GPIO_PIN_2);
    }
    else
    {
      gpio_bit_reset(GPIOD, GPIO_PIN_2);
    }

    //延时
    DelayNus(10);

    //拉高时钟线
    gpio_bit_set(GPIOC, GPIO_PIN_12);

    //延时
    DelayNus(10);

    //获取MISO输入
    readData = (readData << 1) | gpio_input_bit_get(GPIOC, GPIO_PIN_8);

    //发送数据左移
    data = data << 1;
  }

  //返回接收到的数据
  return readData;
}

