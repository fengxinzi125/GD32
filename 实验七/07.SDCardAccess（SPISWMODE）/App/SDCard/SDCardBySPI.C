/*********************************************************************************************************
* 函数名称：SDGetSectorCount
* 函数功能：获取SD卡的总扇区数（扇区数）
* 输入参数：csd：存放CID的内存，至少16Byte
* 输出参数：void
* 返 回 值：0-取容量出错，其他-SD卡的容量(扇区数/512字节)
* 创建日期：2021年07月01日
* 注    意：每扇区的字节数必为512，因为如果不是512，则初始化不能通过
*********************************************************************************************************/
u32 SDGetSectorCount(void)
{
  u8  csd[16];
  u32 capacity;
  u8  n;
  u16 csize;

  //取CSD信息，如果期间出错，返回0
  if(SDGetCSD(csd) != 0)
  {
    return 0;
  }

  //如果为SDHC卡（V2.00的卡），按照下面方式计算
  if((csd[0] & 0xC0) == 0x40)
  {
    csize = csd[9] + ((u16)csd[8] << 8) + 1;

    //得到扇区数
    capacity = (u32)csize << 10;
  }
  
  //V1.XX的卡
  else
  {
    n = (csd[5] & 15) + ((csd[10] & 128) >> 7) + ((csd[9] & 3) << 1) + 2;
    csize = (csd[8] >> 6) + ((u16)csd[7] << 2) + ((u16)(csd[6] & 3) << 10) + 1;

    //得到扇区数
    capacity= (u32)csize << (n - 9);
  }
  return capacity;
}

/*********************************************************************************************************
* 函数名称：InitSDCard
* 函数功能：初始化SD卡
* 输入参数：void
* 输出参数：void
* 返 回 值：0-成功，其他-失败
* 创建日期：2021年07月01日
* 注    意：void
*********************************************************************************************************/
u32 InitSDCard(void)
{
  u8   r1;    //存放SD卡的返回值
  u16 retry;  //用来进行超时计数
  u8  buf[4];  
  u16 i;

  //初始化IO
  InitBSP();

  //设置到低速模式
  SetSpeedLow();

  //发送最少74个脉冲
  for(i = 0;i < 10; i++)
  {
    ReadWriteByte(0xFF);
  }
  
  //进入IDLE状态
  retry = 20;
  do
  {
    r1 = SendCmd(CMD0, 0, 0x95);
  }while((r1 != 0X01) && retry--);

  //开始初始化
  s_iSDCardType = 0;//默认无卡
  if(r1 == 0X01)
  {
    //检查是否是SD V2.0
    if(SendCmd(CMD8,0x1AA,0x87)==1)
    {
      //Get trailing return value of R7 resp
      for(i = 0; i < 4; i++)
      {
        buf[i] = ReadWriteByte(0xFF); 
      }

      //卡是否支持2.7~3.6V
      if(buf[2] == 0X01 && buf[3] == 0xAA)
      {
        retry = 0XFFFE;
        do
        {
          //发送CMD55
          SendCmd(CMD55, 0, 0x01);

          //发送CMD41
          r1 = SendCmd(CMD41, 0x40000000, 0X01);
        }while(r1 && retry--);

        //开始鉴别SD2.0卡版本
        if(retry && SendCmd(CMD58, 0, 0x01) == 0)
        {
          //得到OCR值
          for(i = 0; i < 4; i++)
          {
            buf[i] = ReadWriteByte(0XFF);
          }

          //检查CCS
          if(buf[0] & 0x40)
          {
            s_iSDCardType = SD_TYPE_V2HC;
          }
          else 
          {
            s_iSDCardType = SD_TYPE_V2;
          }
        }
      }
    }
    
    //检查是否是SD V1.x/ MMC V3
    else
    {
      //发送CMD55
      SendCmd(CMD55, 0, 0x01);

      //发送CMD41
      r1 = SendCmd(CMD41, 0, 0x01);
      if(r1 <= 1)
      {
        s_iSDCardType = SD_TYPE_V1;
        retry = 0XFFFE;

        //等待退出IDLE模式
        do
        {
          //发送CMD55
          SendCmd(CMD55, 0, 0x01);

          //发送CMD41
          r1 = SendCmd(CMD41, 0, 0x01);
        }while(r1 && retry--);
      }
      
      //MMC卡不支持CMD55+CMD41识别
      else
      {
        //MMC V3
        s_iSDCardType = SD_TYPE_MMC; 
        retry = 0XFFFE;

        //等待退出IDLE模式
        do 
        {
          //发送CMD1
          r1 = SendCmd(CMD1, 0, 0x01);
        }while(r1 && retry--);
      }

      //错误的卡
      if(retry == 0 || SendCmd(CMD16,512,0X01) != 0)
      {
        s_iSDCardType = SD_TYPE_ERR;
      }
    }
  }

  //取消片选
  DisSelect();

  //进入高速模式
  SetSpeedHigh();
  if(s_iSDCardType)
  {
    return 0;
  }
  else if(r1)
  {
    return r1;
  }

  //其他错误
  return 0xAA;
}

/*********************************************************************************************************
* 函数名称：SDReadSector
* 函数功能：读SD卡
* 输入参数：buf：数据缓存区，sector：扇区，sectorNum:扇区数
* 输出参数：void
* 返 回 值：0-成功，其他-失败
* 创建日期：2021年07月01日
* 注    意：void
*********************************************************************************************************/
u32 SDReadSector(u8* buf, u32 sector, u32 sectorNum)
{
  u8 r1;

  //转换为字节地址
  if(s_iSDCardType != SD_TYPE_V2HC)
  {
    sector <<= 9;
  }

  //读单扇区
  if(1 == sectorNum)
  {
    //发送读命令
    r1 = SendCmd(CMD17, sector, 0x01);

    //指令发送成功
    if(r1 == 0)
    {
      //接收512个字节
      r1 = RecvData(buf, 512);
    }
  }
  
  //读多扇区
  else
  {
    //连续读命令
    r1 = SendCmd(CMD18, sector, 0x01);
    do
    {
      //接收512个字节
      r1 = RecvData(buf, 512);
      buf += 512;
    }while(--sectorNum && 0 == r1);
    
    //发送停止命令
    SendCmd(CMD12, 0, 0x01);
  }

  //取消片选
  DisSelect();
  return r1;
}

/*********************************************************************************************************
* 函数名称：SDWriteSector
* 函数功能：写SD卡
* 输入参数：buf：数据缓存区，sector：扇区，sectorNum:扇区数
* 输出参数：void
* 返 回 值：0-成功，其他-失败
* 创建日期：2021年07月01日
* 注    意：void
*********************************************************************************************************/
u32 SDWriteSector(u8* buf, u32 sector, u32 sectorNum)
{
  u8 r1;

  //转换为字节地址
  if(s_iSDCardType != SD_TYPE_V2HC)
  {
    sector <<= 9;
  }

  //写单扇区
  if(1 == sectorNum)
  {
    //发送写命令
    r1 = SendCmd(CMD24, sector, 0x01);

    //指令发送成功
    if(0 == r1)
    {
      //写512个字节
      r1 = SendBlock(buf, 0xFE);
    }
  }
  
  //写多扇区
  else
  {
    //发送指令
    if(s_iSDCardType != SD_TYPE_MMC)
    {
      SendCmd(CMD55, 0, 0x01);
      SendCmd(CMD23, sectorNum, 0x01);
    }

    //连续写命令
    r1 = SendCmd(CMD25, sector, 0x01);
    if(0 == r1)
    {
      do
      {
        //发送512个字节
        r1 = SendBlock(buf,0xFC);
        buf += 512;
      }while(--sectorNum && r1 == 0);

      //结束
      r1 = SendBlock(0, 0xFD);
    }
  }

  //取消片选
  DisSelect();
  return r1;
}

/*********************************************************************************************************
* 函数名称：SDDetect
* 函数功能：查验SD卡是否插入
* 输入参数：void
* 输出参数：void
* 返 回 值：0-SD卡已插入，其他-SD卡脱落
* 创建日期：2021年07月01日
* 注    意：void
*********************************************************************************************************/
u32 SDDetect(void)
{
  if(0 == gpio_input_bit_get(GPIOD, GPIO_PIN_3))
  {
    return 0;
  }
  else
  {
    return 1;
  }
}
