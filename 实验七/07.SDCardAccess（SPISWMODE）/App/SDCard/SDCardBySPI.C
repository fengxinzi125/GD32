/*********************************************************************************************************
* 函数名称：DisSelect
* 函数功能：取消片选
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 创建日期：2021年07月01日
* 注    意：释放完片选后需要提供额外的8个时钟
*********************************************************************************************************/
static void DisSelect(void)
{
  gpio_bit_set(GPIOC, GPIO_PIN_11);
  ReadWriteByte(0xFF);
}

/*********************************************************************************************************
* 函数名称：EnSelect
* 函数功能：使能片选，并且等待卡准备OK
* 输入参数：void
* 输出参数：void
* 返 回 值：0-成功，1-失败
* 创建日期：2021年07月01日
* 注    意：
*********************************************************************************************************/
static u32 EnSelect(void)
{
  gpio_bit_reset(GPIOC, GPIO_PIN_11);

  //等待卡准备OK
  if(WaitReady() == 0)
  {
    //等待成功
    return 0;
  }

  //等待失败
  DisSelect();
  return 1;
}

/*********************************************************************************************************
* 函数名称：WaitReady
* 函数功能：使能片选，并且等待卡准备OK
* 输入参数：void
* 输出参数：void
* 返 回 值：0-准备好了，其他-错误代码
* 创建日期：2021年07月01日
* 注    意：
*********************************************************************************************************/
static u32 WaitReady(void)
{
  u32 t = 0;

  //超时等待
  while(t < 0xFFFFFF)
  {
    if(ReadWriteByte(0xFF) == 0xFF)
    {
      return 0;
    }
    t++;
  }

  //等待超时
  return 1;
}

/*********************************************************************************************************
* 函数名称：GetResponse
* 函数功能：等待SD卡回应
* 输入参数：response：要得到的回应值
* 输出参数：void
* 返 回 值：0-成功得到了该回应值，其他-得到回应值失败
* 创建日期：2021年07月01日
* 注    意：
*********************************************************************************************************/
static u32 GetResponse(u8 response)
{
  //等待次数
  u16 count = 0xFFFF;

  //等待得到准确的回应
  while ((ReadWriteByte(0xFF) != response) && count)
  {
    count--;
  }

  //得到回应失败
  if(0 == count)
  {
    return MSD_RESPONSE_FAILURE;
  }

  //正确回应
  else 
  {
    return MSD_RESPONSE_NO_ERROR;
  }
}

/*********************************************************************************************************
* 函数名称：RecvData
* 函数功能：从SD卡读取一个数据包的内容
* 输入参数：buf:数据缓存区，len:要读取的数据长度
* 输出参数：void
* 返 回 值：0-成功，其他-失败
* 创建日期：2021年07月01日
* 注    意：
*********************************************************************************************************/
static u32 RecvData(u8* buf, u32 len)
{
  //等待SD卡发回数据起始令牌0xFE
  if(GetResponse(0xFE))
  {
    return 1;
  }

  //开始接收数据
  while(len--)
  {
    *buf = ReadWriteByte(0xFF);
    buf++;
  }

  //下面是2个伪CRC（dummy CRC）
  ReadWriteByte(0xFF);
  ReadWriteByte(0xFF);

  //读取成功
  return 0;
}

/*********************************************************************************************************
* 函数名称：SendBlock
* 函数功能：向SD卡写入一个数据包的内容 512字节
* 输入参数：buf:数据缓存区，cmd:指令
* 输出参数：void
* 返 回 值：0-成功，其他-失败
* 创建日期：2021年07月01日
* 注    意：
*********************************************************************************************************/
static u32 SendBlock(u8*buf, u8 cmd)
{
  u16 t;

  //等待准备失效
  if(WaitReady())
  {
    return 1;
  }

  //发送命令
  ReadWriteByte(cmd);

  //不是结束指令
  if(cmd != 0XFD)
  {
    for(t = 0; t < 512; t++)
    {
      ReadWriteByte(buf[t]);
    }

    //忽略crc
    ReadWriteByte(0xFF);
    ReadWriteByte(0xFF);

    //接收响应
    t = ReadWriteByte(0xFF);
    if((t & 0x1F) != 0x05)
    {
      return 2;//响应错误
    }
  }
  
  //写入成功
  return 0;
}

/*********************************************************************************************************
* 函数名称：SendCmd
* 函数功能：向SD卡发送一个命令
* 输入参数：cmd：命令，arg：命令参数，crc：校验值
* 输出参数：void
* 返 回 值：SD卡返回的响应
* 创建日期：2021年07月01日
* 注    意：
*********************************************************************************************************/
static u32 SendCmd(u8 cmd, u32 arg, u8 crc)
{
  u8 r1;
  u8 retry;

  //取消上次片选
  DisSelect();

  //使能片选
  if(EnSelect())
  {
    return 0xFF; 
  }

  //发送命令
  ReadWriteByte(cmd | 0x40);
  ReadWriteByte(arg >> 24);
  ReadWriteByte(arg >> 16);
  ReadWriteByte(arg >> 8);
  ReadWriteByte(arg);
  ReadWriteByte(crc);
  if(cmd == CMD12)
  {
    ReadWriteByte(0xFF);
  }

  //等待响应，或超时退出
  retry = 0X1F;
  do
  {
    r1 = ReadWriteByte(0xFF);
  }while((r1 & 0x80) && retry--);

  //返回状态值
  return r1;
}

